// Feature icon mapper
export function FeatureIcon({ icon, size = 24, className }: { icon: string; size?: number; className?: string }) {
  switch (icon) {
    case 'accident': return <IconAlertTriangle size={size} className={className} />
    case 'title': return <IconFileText size={size} className={className} />
    case 'mileage': return <IconGauge size={size} className={className} />
    case 'theft': return <IconLock size={size} className={className} />
    case 'ownership': return <IconUsers size={size} className={className} />
    case 'recalls': return <IconRefreshCw size={size} className={className} />
    case 'service': return <IconWrench size={size} className={className} />
    case 'value': return <IconDollarSign size={size} className={className} />
    default: return <IconShield size={size} className={className} />
  }
}
